let fail = 0;
function mustEqual(tag, input, expected) {
  const got = koFix(input);
  if (got !== expected) {
    fail++;
    console.log(`FAIL [${tag}]`);
    console.log(`  in : ${input}`);
    console.log(`  out: ${got}`);
    console.log(`  exp: ${expected}`);
  }
}

